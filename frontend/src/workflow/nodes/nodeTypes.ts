export interface WorkflowNodeConfig {
  [key: string]: unknown;
}

export interface WorkflowNodeTypeConfig {
  type: string;
  label: string;
  description: string;
  category: string;
  icon: React.ComponentType<{ className?: string }>;
  color: string;
  inputHandles: string[];
  outputHandles: string[];
  defaultConfig: WorkflowNodeConfig;
}

export interface WorkflowNodeData {
  id: string;
  type: string;
  label: string;
  description?: string;
  config: WorkflowNodeConfig;
  status?: "idle" | "running" | "success" | "error" | "skipped";
  error?: string;
  width?: number;
  height?: number;
  [key: string]: unknown;
}

export interface WorkflowEdgeData {
  id: string;
  source: string;
  target: string;
  sourceHandle?: string;
  targetHandle?: string;
  label?: string;
  animated?: boolean;
  [key: string]: unknown;
}

export interface WorkflowExecutionState {
  runId: string;
  status: "idle" | "running" | "completed" | "failed";
  nodeStatuses: Record<string, "idle" | "running" | "success" | "error" | "skipped">;
  nodeOutputs: Record<string, unknown>;
  startedAt?: Date;
  completedAt?: Date;
  error?: string;
}

